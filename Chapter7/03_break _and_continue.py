# break statement
for i in range(0,100):
   if(i==30):
     break #it ends/exit the loop    
   print(i)

# continue statement
for i in range(0,100):
   if(i==30):
     continue #it skips the iteration/means it only not print the given value
   print(i)
# Pass statement
for i in range(100):
   pass  #pass is a null statement in python,it instruct do nothing

i=1
while(i<40):
   print(i)
   i+=1
