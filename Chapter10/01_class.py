class employee:    #this is a class
    language="python"
    salary=1000000

lol=employee()   #lol is a object here
lol.name="Ali"
print(lol.name ,lol.salary,lol.language)

#another object
hassan=employee()
hassan.name="Hassan"   #this is a object/instance attribute  
print(hassan.name,hassan.salary,hassan.language)
 #here name is object attribute and salary and language is a class attribute as it belongs to a class